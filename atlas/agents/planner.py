import json
from typing import Any

from openai import OpenAI

from config import (
    MODEL,
    OPENAI_API_KEY,
)


client = OpenAI(
    api_key=OPENAI_API_KEY,
)


PLAN_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "primary_keyword": {
            "type": "string",
        },
        "search_intent": {
            "type": "string",
        },
        "target_reader": {
            "type": "string",
        },
        "reader_problem": {
            "type": "string",
        },
        "reader_before_state": {
            "type": "string",
        },
        "solution_angle": {
            "type": "string",
        },
        "primary_decision": {
            "type": "string",
        },
        "reader_after_state": {
            "type": "string",
        },
        "article_goal": {
            "type": "string",
        },
        "suggested_title": {
            "type": "string",
        },
        "outline": {
            "type": "array",
            "items": {
                "type": "string",
            },
            "minItems": 4,
            "maxItems": 8,
        },
        "related_keywords": {
            "type": "array",
            "items": {
                "type": "string",
            },
            "minItems": 3,
            "maxItems": 8,
        },
        "affiliate_service": {
            "type": "string",
        },
        "content_angle": {
            "type": "string",
        },
    },
    "required": [
        "primary_keyword",
        "search_intent",
        "target_reader",
        "reader_problem",
        "reader_before_state",
        "solution_angle",
        "primary_decision",
        "reader_after_state",
        "article_goal",
        "suggested_title",
        "outline",
        "related_keywords",
        "affiliate_service",
        "content_angle",
    ],
    "additionalProperties": False,
}


def create_article_plan(
    topic: str,
    editorial_brief: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """
    テーマから、
    検索意図と読者の問題解決を重視した
    Alsivo向け記事企画を作成する。
    """

    cleaned_topic = topic.strip()

    if not cleaned_topic:
        raise ValueError(
            "テーマを入力してください。"
        )

    brief_text = json.dumps(
        editorial_brief or {},
        ensure_ascii=False,
        indent=2,
    )

    response = client.responses.create(
        model=MODEL,
        store=False,
        instructions=(

            # =================================================
            # 基本役割
            # =================================================

            "あなたはAIツール情報メディアAlsivoの"
            "編集者です。"

            "入力されたテーマから、"
            "検索ユーザーの疑問・悩み・判断課題を解決する"
            "記事企画を作成してください。"

            "単にテーマを説明する記事ではなく、"
            "そのキーワードを検索する人が"
            "『なぜ今それを検索しているのか』"
            "『何に困っているのか』"
            "『何が分かれば次の行動を取れるのか』"
            "を考えてください。"

            "Alsivoの記事は、"
            "情報を並べること自体を目的にせず、"
            "読者が問題を整理し、"
            "判断し、必要なら具体的な行動へ進めることを"
            "目的とします。"

            "編集長指示が渡された場合は、"
            "affiliate_service、content_angle、target_reader_problem、"
            "reader_after_stateを企画へ具体的に反映してください。"
            "既存記事と同じサービスを扱う場合でも、"
            "検索意図、対象読者、悩み、利用場面の少なくとも1つを"
            "明確に変え、単なる言い換え記事にしないでください。"
            "案件記事は、案件の魅力を前向きに紹介する切り口、または"
            "案件によって解決できる読者の具体的な悩みに着目する切り口の"
            "どちらかで設計してください。"
            "メリットを中心に、活用場面、向いている人、読後に得られる変化を"
            "具体的に伝えてください。デメリットは必要な範囲で簡潔に扱えますが、"
            "返金条件、料金表示の不一致、未掲載情報などの細かな否定材料を"
            "結論や要点の中心に置かないでください。"
            "競合サービス、代替サービス、別の選択肢を紹介・推奨する"
            "見出しや構成は絶対に作らないでください。"
            "事実を曲げる、重要な条件を隠す、根拠なく効果を断定することは"
            "禁止します。"

            "affiliate_serviceには編集長指示の案件名をそのまま入れ、"
            "案件指定がない場合は空文字にしてください。"
            "content_angleには今回の記事固有の切り口を入れ、"
            "案件指定がない場合もテーマに即した切り口を入れてください。"

            # =================================================
            # 各フィールドの役割
            # =================================================

            "search_intent、target_reader、reader_problem、"
            "reader_before_state、solution_angle、"
            "primary_decision、reader_after_state、"
            "article_goalは、それぞれ役割が異なります。"

            "同じ内容を言い換えて"
            "繰り返さないでください。"

            # -------------------------------------------------
            # primary_keyword
            # -------------------------------------------------

            "primary_keywordには、"
            "記事が最も直接答えるべき"
            "中心的な検索キーワードを設定してください。"

            "入力テーマが十分に具体的な場合は、"
            "不必要に別テーマへ変更しないでください。"

            "過度に広いテーマの場合のみ、"
            "検索意図と読者の悩みが明確になる範囲で"
            "テーマを絞り込んでください。"

            # -------------------------------------------------
            # search_intent
            # -------------------------------------------------

            "search_intentには、"
            "検索ユーザーが最終的に何を知りたい、"
            "比較したい、判断したい、解決したい、"
            "または実行したいのかを"
            "具体的に記述してください。"

            "検索結果を見て終わるのではなく、"
            "その情報を使って読者が"
            "何を決めようとしているのかまで"
            "可能な限り明確にしてください。"

            # -------------------------------------------------
            # target_reader
            # -------------------------------------------------

            "target_readerには、"
            "どのような状況の人がこの記事を読むのかを"
            "具体的に記述してください。"

            "単に『初心者』『AIユーザー』"
            "『会社員』のような"
            "広すぎる表現だけにしないでください。"

            "利用状況、困っている場面、"
            "経験レベル、判断段階などを"
            "自然に含めてください。"

            # -------------------------------------------------
            # reader_problem
            # -------------------------------------------------

            "reader_problemには、"
            "検索時点で読者が何に困っているのか、"
            "何が分からず次の行動を取れないのかを"
            "具体的に記述してください。"

            "機能を知らない、料金が分からない、"
            "比較できない、設定方法が分からない、"
            "エラーで作業が止まっている、"
            "どのAIを選べばよいか分からない、"
            "作業に時間がかかっている、"
            "といった実際の困りごとを"
            "記事テーマに応じて具体化してください。"

            "読者本人が読んだときに"
            "『まさにこれで困っている』"
            "と感じられる粒度を目指してください。"

            # -------------------------------------------------
            # reader_before_state
            # -------------------------------------------------

            "reader_before_stateには、"
            "この記事を読む前の読者の状態を"
            "簡潔に記述してください。"

            "何が分からないのか、"
            "何を迷っているのか、"
            "どこで作業が止まっているのか、"
            "どの判断ができていないのかを"
            "状態として表現してください。"

            "reader_problemよりも、"
            "読者の現在地を一段短く"
            "まとめるイメージです。"

            # -------------------------------------------------
            # solution_angle
            # -------------------------------------------------

            "solution_angleには、"
            "この記事がreader_problemを"
            "どのような切り口で解決するのかを"
            "具体的に記述してください。"

            "単に『詳しく解説する』"
            "『比較する』だけでは不十分です。"

            "例えば、"
            "料金と利用上限を並べて"
            "利用頻度別に判断できるようにする、"
            "エラー原因を切り分けて"
            "今すぐ試せる対処順に示す、"
            "用途別にAIツールの向き不向きを整理して"
            "選択しやすくする、"
            "といった解決方法を記述してください。"

            "記事全体の問題解決アプローチとして"
            "使える内容にしてください。"

            # -------------------------------------------------
            # primary_decision
            # -------------------------------------------------

            "primary_decisionには、"
            "この記事を読んだ結果として、"
            "読者が最も重要な何を"
            "判断できるようになるべきかを"
            "1つに絞って記述してください。"

            "比較記事なら"
            "『どちらを選ぶべきか』、"
            "料金記事なら"
            "『課金する価値があるか』、"
            "How-to記事なら"
            "『どの方法で進めるか』、"
            "トラブル記事なら"
            "『どの対処を今実行するか』"
            "などです。"

            "記事テーマによって、"
            "明確な意思決定が不要な場合は、"
            "最も重要な実行判断や確認判断を"
            "設定してください。"

            # -------------------------------------------------
            # reader_after_state
            # -------------------------------------------------

            "reader_after_stateには、"
            "記事を読み終えた後に"
            "読者がどのような状態になっているべきかを"
            "具体的に記述してください。"

            "単に『理解できる』ではなく、"
            "自分に必要なプランを選べる、"
            "エラーへ対処できる、"
            "ツールを選んで使い始められる、"
            "無料版で十分か課金すべきか判断できる、"
            "といった変化を表現してください。"

            "reader_before_stateとの違いが"
            "明確になるようにしてください。"

            # -------------------------------------------------
            # article_goal
            # -------------------------------------------------

            "article_goalには、"
            "記事全体として達成すべき編集上のゴールを"
            "記述してください。"

            "reader_after_stateより少し広い視点で、"
            "読者が何を理解し、"
            "何を判断し、"
            "必要なら何を実行できる状態にするのかを"
            "まとめてください。"

            # =================================================
            # タイトル
            # =================================================

            "suggested_titleは、"
            "検索ユーザーが"
            "この記事で何を解決できるか"
            "分かるタイトルにしてください。"

            "検索キーワードは、"
            "不自然にならない範囲で"
            "適切に反映してください。"

            "タイトルだけで"
            "単なる用語解説なのか、"
            "比較・判断・解決記事なのかが"
            "できるだけ分かるようにしてください。"

            "ただし、"
            "『困っていませんか？』"
            "『知らないと損』"
            "『絶対』"
            "『今すぐ』"
            "などの煽り表現を"
            "タイトルへ機械的に追加しないでください。"

            "タイトルに年号を"
            "勝手に入れないでください。"

            # =================================================
            # Outline
            # =================================================

            "outlineは、"
            "検索ユーザーが"
            "知りたい順番、"
            "解決に必要な順番を"
            "優先して設計してください。"

            "記事冒頭では、"
            "reader_problemを読者が"
            "自分事として認識でき、"
            "この記事でどう解決できるかが"
            "分かる導入を想定してください。"

            "ただしoutlineへ"
            "『こんなことで困っていませんか？』"
            "という定型見出しを"
            "必ず作る必要はありません。"

            "導入文の中で自然に"
            "読者の困りごとを提示する記事も"
            "許可してください。"

            "検索意図に対する主要な答えを"
            "記事前半で提示できる構成にしてください。"

            "重要な結論を"
            "最後まで引っ張らないでください。"

            "主要な答えを提示した後に、"
            "その理由、仕組み、比較、具体例、"
            "手順、注意点などを配置してください。"

            "記事全体として、"
            "reader_before_stateから"
            "reader_after_stateへ"
            "自然に進む流れを意識してください。"

            "solution_angleが"
            "記事構成へ実際に反映されるようにしてください。"

            "primary_decisionを"
            "読者が無理なく行えるように、"
            "判断材料を必要な順番で"
            "配置してください。"

            # -------------------------------------------------
            # テーマ別構成
            # -------------------------------------------------

            "トラブル解決テーマでは、"
            "原因の詳しい説明より先に"
            "読者が今取るべき行動を"
            "配置してください。"

            "How-toテーマでは、"
            "実行手順を優先してください。"

            "比較テーマでは、"
            "違いを並べるだけでなく、"
            "どのような人が"
            "どちらを選ぶべきか判断できる"
            "構成にしてください。"

            "料金・プランテーマでは、"
            "料金そのものだけでなく、"
            "費用に見合うか、"
            "どのプランを選ぶべきかを"
            "判断できる構成にしてください。"

            "おすすめ記事では、"
            "ツールを並べるだけでなく、"
            "用途・目的・困りごと別に"
            "選べる構成にしてください。"

            "初心者向け記事では、"
            "用語説明を増やしすぎるより、"
            "最初に何をすればよいか、"
            "何から試せばよいかが"
            "分かる構成を優先してください。"

            # =================================================
            # 定型化の防止
            # =================================================

            "すべての記事を"
            "同じoutlineにしないでください。"

            "『概要』『特徴』『メリット』"
            "『デメリット』『まとめ』"
            "のような定型構成を、"
            "テーマに関係なく"
            "機械的に使用しないでください。"

            "『こんなことで困っていませんか？』"
            "という表現も、"
            "すべての記事へ"
            "機械的に入れないでください。"

            "読者への寄り添いは、"
            "具体的な状況描写や問いかけを"
            "自然に使用してください。"

            "過度に感情へ訴えたり、"
            "不安を煽ったり、"
            "広告的な文章にしないでください。"

            "outlineの各項目は、"
            "その章で何を解決するのか、"
            "何を判断できるようにするのかが"
            "分かる具体的な表現にしてください。"

            # =================================================
            # Related keywords
            # =================================================

            "related_keywordsには、"
            "primary_keywordと検索意図が近く、"
            "記事内で自然に扱う価値のある"
            "関連キーワードだけを入れてください。"

            "検索流入を狙うためだけに、"
            "検索意図の異なるキーワードを"
            "無理に追加しないでください。"

            # =================================================
            # 最終整合確認
            # =================================================

            "企画を返す直前に、"
            "reader_problemが"
            "reader_before_stateへ自然につながり、"
            "solution_angleによって解決され、"
            "primary_decisionを経て"
            "reader_after_stateへ到達する"
            "一貫した設計になっているか"
            "確認してください。"

            "search_intent、article_goal、outlineも"
            "この問題解決の流れと"
            "矛盾していないことを確認してください。"
        ),
        input=(
            "次のテーマから記事企画を"
            "作成してください。\n\n"
            f"テーマ：{cleaned_topic}\n\n"
            "編集長指示：\n"
            f"{brief_text}"
        ),
        text={
            "format": {
                "type": "json_schema",
                "name": "alsivo_article_plan",
                "schema": PLAN_SCHEMA,
                "strict": True,
            }
        },
    )

    if not response.output_text:
        raise RuntimeError(
            "記事企画を取得できませんでした。"
        )

    try:
        return json.loads(
            response.output_text
        )

    except json.JSONDecodeError as error:
        raise RuntimeError(
            "記事企画のJSON変換に失敗しました。"
        ) from error
