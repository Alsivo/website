def build_article_schema(
    research: dict[str, Any],
) -> dict[str, Any]:
    """記事生成時に使用する動的Schemaを作る。"""

    source_ids = [
        str(
            source.get(
                "id",
                "",
            )
        ).strip()
        for source in research.get(
            "sources",
            [],
        )
        if (
            isinstance(
                source,
                dict,
            )
            and str(
                source.get(
                    "id",
                    "",
                )
            ).strip()
        )
    ]

    if not source_ids:
        raise ValueError(
            "記事生成に利用できる"
            "出典IDがありません。"
        )

    affiliate_tool_names = (
        get_affiliate_tool_names()
    )

    schema = deepcopy(
        ARTICLE_SCHEMA
    )

    # 実在する出典IDだけを選択可能にする
    schema[
        "properties"
    ][
        "used_source_ids"
    ][
        "items"
    ] = {
        "type": "string",
        "enum": source_ids,
    }

    schema[
        "properties"
    ][
        "used_source_ids"
    ][
        "maxItems"
    ] = min(
        10,
        len(
            source_ids
        ),
    )

    # リンク台帳に登録されたサービスだけを
    # recommended_toolsで選択可能にする
    schema[
        "properties"
    ][
        "recommended_tools"
    ][
        "items"
    ] = {
        "type": "string",
        "enum":
            affiliate_tool_names,
    }

    schema[
        "properties"
    ][
        "recommended_tools"
    ][
        "maxItems"
    ] = min(
        5,
        len(
            affiliate_tool_names
        ),
    )

    return schema


