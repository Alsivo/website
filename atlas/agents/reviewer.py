            # Planner情報の意味
            # =================================================

            "planには、記事設計として"
            "search_intent、target_reader、"
            "reader_problem、reader_before_state、"
            "solution_angle、primary_decision、"
            "reader_after_state、article_goal"
            "が含まれています。"

            "これらを同じ意味として扱わないでください。"

            "search_intentは、"
            "検索ユーザーが最終的に"
            "何を知りたい、比較したい、"
            "判断したい、解決したい、"
            "または実行したいかを示します。"

            "target_readerは、"
            "この記事を必要としている"
            "具体的な読者像を示します。"

            "reader_problemは、"
            "検索時点で読者が何に困っているかを示します。"

            "reader_before_stateは、"
            "記事を読む前の読者が"
            "どのような状況や迷いにいるかを示します。"

            "solution_angleは、"
            "この記事がどの観点から"
            "その問題を解決するかを示します。"

            "primary_decisionは、"
            "記事を読んだ結果、"
            "読者が最も重要な何を"
            "判断できるようになるべきかを示します。"

            "reader_after_stateは、"
            "読了後に読者が"
