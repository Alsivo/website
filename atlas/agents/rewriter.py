def build_rewrite_schema(
    research: dict[str, Any],
) -> dict[str, Any]:
    """
    実在する出典IDと
    登録済みAffiliateサービスだけを
    使用可能にする動的Schemaを作る。
    """

    source_ids = [
        str(
            source.get(
                "id",
                "",
            )
        ).strip()
        for source in research.get(
            "sources",
            [],
        )
        if (
            isinstance(
                source,
                dict,
            )
            and str(
                source.get(
                    "id",
                    "",
                )
            ).strip()
        )
    ]

    if not source_ids:
        raise ValueError(
            "リライトに利用できる"
            "出典IDがありません。"
        )

    affiliate_tools = (
        get_affiliate_tool_names()
    )

    schema = deepcopy(
        REWRITE_SCHEMA
    )

    # -----------------------------------------------------
    # Researcherが取得した実在出典のみ許可
    # -----------------------------------------------------

    schema[
        "properties"
    ][
        "used_source_ids"
    ][
        "items"
    ] = {
        "type": "string",
        "enum": source_ids,
    }

    schema[
        "properties"
    ][
        "used_source_ids"
    ][
        "maxItems"
    ] = min(
        15,
        len(source_ids),
    )

    # -----------------------------------------------------
    # Affiliate Registry登録済みサービスのみ許可
    # -----------------------------------------------------

    schema[
        "properties"
    ][
        "recommended_tools"
    ][
        "items"
    ] = {
        "type": "string",
        "enum": affiliate_tools,
    }

    schema[
        "properties"
    ][
        "recommended_tools"
    ][
        "maxItems"
    ] = min(
        5,
        len(affiliate_tools),
    )

    return schema


